"""
Injection du style CSS professionnel dans Streamlit.
"""

import streamlit as st
from pathlib import Path


def apply_style():
    """Charge et injecte le CSS personnalisé."""
    css_path = Path(__file__).resolve().parents[2] / ".streamlit" / "style.css"
    with open(css_path, "r", encoding="utf-8") as f:
        css = f.read()
    st.markdown(f"<style>{css}</style>", unsafe_allow_html=True)


def render_header(title: str, subtitle: str = "", icon_svg: str = ""):
    """Affiche un header de page avec icône SVG professionnelle."""
    st.markdown(
        f"""
        <div class="app-header">
            <div class="app-header-icon">{icon_svg}</div>
            <div>
                <div class="app-header-title">{title}</div>
                <div class="app-header-subtitle">{subtitle}</div>
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )


